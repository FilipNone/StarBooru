#!/usr/bin/env python3
"""Writes crates/core/src/ai_files.rs: every file of every AI model, pinned to a
Hugging Face commit and a SHA-256. Run it to move a model to a newer revision:
    python3 -I tools/ai-catalog/pin.py > crates/core/src/ai_files.rs
"""
import hashlib, json, sys, urllib.request

UA = {"User-Agent": "starbooru-catalog"}
OPUS = "ja-en zh-en ko-en ru-en fr-en de-en es-en it-en en-it en-fr en-de en-es en-ru en-zh".split()
Q = ["onnx/encoder_model_quantized.onnx", "onnx/decoder_model_merged_quantized.onnx", "tokenizer.json", "config.json"]
MODELS = [
    ("TRESNET", "deepghs/ml-danbooru-onnx", ["TResnet-D-FLq_ema_6-30000.onnx", "tags.csv"]),
    ("WD_SWINV2", "SmilingWolf/wd-swinv2-tagger-v3", ["model.onnx", "selected_tags.csv"]),
    ("WD_EVA02", "SmilingWolf/wd-eva02-large-tagger-v3", ["model.onnx", "selected_tags.csv"]),
    ("M2M", "Xenova/m2m100_418M", Q),
    ("GEMMA", "onnx-community/translategemma-text-4b-it-ONNX",
     ["onnx/model_q4.onnx", "onnx/model_q4.onnx_data", "onnx/model_q4.onnx_data_1", "tokenizer.json"]),
    ("DET_SMALL", "ogkalu/comic-text-and-bubble-detector", ["detector-v4-s_int8.onnx"]),
    ("DET_LARGE", "ogkalu/comic-text-and-bubble-detector", ["detector_int8.onnx"]),
    ("MANGA_OCR", "l0wgear/manga-ocr-2025-onnx", ["encoder_model.onnx", "decoder_model.onnx", "vocab.txt"]),
]
for pair in OPUS:
    MODELS.append((f"OPUS_{pair.replace('-', '_').upper()}", f"Xenova/opus-mt-{pair}", Q))


def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=120)


print("//! Generated by `tools/ai-catalog/pin.py`. Do not edit.\n\nuse super::ai_catalog::ModelFile;\n")
for const, repo, paths in MODELS:
    rev = json.load(get(f"https://huggingface.co/api/models/{repo}"))["sha"]
    tree = {f["path"]: f for f in json.load(get(f"https://huggingface.co/api/models/{repo}/tree/{rev}?recursive=1"))}
    print(f"pub const {const}: &[ModelFile] = &[")
    for path in paths:
        entry = tree[path]
        if entry.get("lfs"):
            sha = entry["lfs"]["oid"]
        else:
            sha = hashlib.sha256(get(f"https://huggingface.co/{repo}/resolve/{rev}/{path}").read()).hexdigest()
        print(f'    ModelFile {{\n        repo: "{repo}",\n        rev: "{rev}",\n        path: "{path}",\n        sha256: "{sha}",\n        size: {entry["size"]},\n    }},')
    print("];\n")
    print(f"pinned {const}", file=sys.stderr, flush=True)
