#[component]
pub fn Ico(icon: Icon, #[props(default = 24)] size: u32) -> Element {
    rsx! {
        svg {
            class: "icon",
            width: "{size}",
            height: "{size}",
            view_box: "0 0 24 24",
            fill: "currentColor",
            "aria-hidden": "true",
            match icon.shape() {
                Shape::Fill(d) => rsx! { path { d } },
                Shape::EvenOdd(d) => rsx! { path { fill_rule: "evenodd", d } },
                Shape::Stroke(width, d) => rsx! {
                    path {
                        fill: "none",
                        stroke: "currentColor",
                        stroke_width: width,
                        stroke_linecap: "round",
                        stroke_linejoin: "round",
                        d,
                    }
                },
            }
        }
    }
}

